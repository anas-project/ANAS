func TestRenderEnvRequiresTheDatabaseAndForgejoBinding(t *testing.T) {
	calculated, err := runHook(t, "calculate", baseEnv(), nil)
	if err != nil {
		t.Fatalf("calculate: %v", err)
	}
	env := baseEnv()
	for key, value := range calculated.Env {
		env[key] = value
	}
	for key, value := range calculated.Secrets {
		env[key] = value
	}
	if _, err := runHook(t, "render_env", env, nil); err == nil {
		t.Fatal("render_env succeeded without a database binding")
	}
	for key, value := range map[string]string{
		"AI_AGENT_DB_HOST": "postgres", "AI_AGENT_DB_NAME": "ai_agent",
		"AI_AGENT_DB_USERNAME": "ai_agent", "AI_AGENT_DB_PASSWORD": "secret",
		"AI_AGENT_NETWORK_DB": "anas_db", "TZ": "UTC",
	} {
		env[key] = value
	}
	if _, err := runHook(t, "render_env", env, nil); err == nil {
		t.Fatal("render_env succeeded without FORGEJO_DOMAIN_FULL")
	}
	env["FORGEJO_DOMAIN_FULL"] = "http://git.example"
	if _, err := runHook(t, "render_env", env, nil); err == nil {
		t.Fatal("render_env accepted a plaintext Forgejo URL")
	}
	env["FORGEJO_DOMAIN_FULL"] = "https://git.example.test:8443"
	if _, err := runHook(t, "render_env", env, nil); err != nil {
		t.Fatalf("render_env: %v", err)
	}
}

// AGENT-R-010: the administrator password is passed to the Forgejo entrypoint
// on stdin, and the helper's output is never echoed -- an error that quoted it
// would put the password in the deployment log.
func TestAdminReconciliationNeverEchoesTheHelperOutput(t *testing.T) {
	original := runContainerHelper
	t.Cleanup(func() { runContainerHelper = original })

	var sent []byte
	var argv []string
	runContainerHelper = func(payload []byte, name string, args ...string) ([]byte, error) {
		sent = payload
		argv = append([]string{name}, args...)
		return nil, nil
	}
	env := baseEnv()
	env["AI_AGENT_FORGEJO_ADMIN_PASSWORD"] = "the-administrator-password"
	if err := reconcileAdminAccount(env); err != nil {
		t.Fatalf("reconcileAdminAccount: %v", err)
	}
	var input localAdminInput
	if err := json.Unmarshal(sent, &input); err != nil {
		t.Fatalf("payload is not the managed-account input: %v", err)
	}
	if input.Username != adminAccount || input.Password != "the-administrator-password" {
		t.Fatalf("payload = %+v, want the dedicated administrator", input)
	}
	if strings.Join(argv, " ") != "docker exec -i --user 1000:1000 anas_forgejo /usr/local/bin/anas-forgejo-entrypoint local-admin" {
		t.Fatalf("argv = %v", argv)
	}
	for _, arg := range argv {
		if strings.Contains(arg, "the-administrator-password") {
			t.Fatal("the password was passed as a command-line argument, where every process on the host can read it")
		}
	}

	runContainerHelper = func([]byte, string, ...string) ([]byte, error) {
		return []byte("forgejo said: password the-administrator-password rejected"), errFailed{}
	}
	err := reconcileAdminAccount(env)
	if err == nil {
		t.Fatal("reconcileAdminAccount reported success although the helper failed")
	}
	if strings.Contains(err.Error(), "the-administrator-password") {
		t.Fatalf("the error echoed the password: %q", err)
	}
}

type errFailed struct{}

func (errFailed) Error() string { return "exit status 1" }

