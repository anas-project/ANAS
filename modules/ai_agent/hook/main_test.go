func runHook(t *testing.T, phase string, env map[string]string, secrets map[string]string) (hookResponse, error) {
	t.Helper()
	if secrets == nil {
		secrets = map[string]string{}
	}
	return handle(hookRequest{
		ABI: "anas.module-hook/v1", Phase: phase, Module: "ai_agent", Env: env, Secrets: secrets,
	})
}

func TestCalculateDerivesDomainAndWebhookURL(t *testing.T) {
	resp, err := runHook(t, "calculate", baseEnv(), nil)
	if err != nil {
		t.Fatalf("calculate: %v", err)
	}
	if got := resp.Env["AI_AGENT_DOMAIN"]; got != "agent.example.test" {
		t.Fatalf("domain = %q", got)
	}
	// The webhook URL is derived, never configured: an operator who could set it
	// could point Forgejo at a host this deployment does not control.
	want := "https://agent.example.test:8443/forgejo/webhook"
	if got := resp.Env["AI_AGENT_WEBHOOK_URL"]; got != want {
		t.Fatalf("webhook URL = %q, want %q", got, want)
	}
	if got := resp.Env["AI_AGENT_FORGEJO_ADMIN_USERNAME"]; got != adminAccount {
		t.Fatalf("administrator = %q, want %q", got, adminAccount)
	}
}

// AGENT-R-009: the signing key is generated by ANAS, not supplied by an
// operator, and it is stable once generated.
func TestCalculateGeneratesAndKeepsSecrets(t *testing.T) {
	resp, err := runHook(t, "calculate", baseEnv(), nil)
	if err != nil {
		t.Fatalf("calculate: %v", err)
	}
	secret := resp.Secrets["AI_AGENT_WEBHOOK_SECRET"]
	password := resp.Secrets["AI_AGENT_FORGEJO_ADMIN_PASSWORD"]
	if len(secret) != 64 || len(password) != 64 {
		t.Fatalf("generated secret/password lengths = %d/%d, want 64 hex characters each", len(secret), len(password))
	}
	if secret == password {
		t.Fatal("the webhook secret and the administrator password are the same value")
	}
	again, err := runHook(t, "calculate", baseEnv(), map[string]string{
		"AI_AGENT_WEBHOOK_SECRET": secret, "AI_AGENT_FORGEJO_ADMIN_PASSWORD": password,
	})
	if err != nil {
		t.Fatalf("second calculate: %v", err)
	}
	if _, regenerated := again.Secrets["AI_AGENT_WEBHOOK_SECRET"]; regenerated {
		t.Fatal("an existing webhook secret was regenerated, which would orphan the registered hook")
	}
}

// AGENT-R-004: `enabled` may not be turned on without every precondition.
func TestEnabledRefusesWithoutItsPreconditions(t *testing.T) {
	for key, want := range map[string]string{
		"AI_AGENT_REPOSITORY_ALLOWLIST":   "AI_AGENT_REPOSITORY_ALLOWLIST",
		"AI_AGENT_RUNTIMES":               "AI_AGENT_RUNTIMES",
		"AI_AGENT_RUNTIME_IMAGES":         "AI_AGENT_RUNTIME_IMAGES",
		computeLeasePrefix + "ENDPOINT":   "compute binding",
		computeLeasePrefix + "CLIENT_KEY": "compute binding",
	} {
		t.Run(key, func(t *testing.T) {
			env := baseEnv()
			delete(env, key)
			_, err := runHook(t, "calculate", env, nil)
			if err == nil {
				t.Fatalf("calculate succeeded with %s missing", key)
			}
			if !strings.Contains(err.Error(), want) {
				t.Fatalf("error %q does not name the missing %q", err, want)
			}
		})
	}
}

