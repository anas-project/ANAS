func TestCredentialOperationsAreScopedToTheWebhookSecret(t *testing.T) {
	original := credentialDockerInspect
	t.Cleanup(func() { credentialDockerInspect = original })
	credentialDockerInspect = func(string) ([]byte, error) {
		return json.Marshal([]string{"AI_AGENT_WEBHOOK_SECRET=desired-value"})
	}
	req := hookRequest{
		ABI: "anas.module-hook/v1", Phase: "credential_reconcile", Module: "ai_agent",
		Env:     map[string]string{"CONTAINER_PREFIX": "anas_"},
		Secrets: map[string]string{"CANDIDATE": "desired-value"},
		Credential: &credentialOperation{
			Handler: "reconcile-ai-agent-webhook-secret", CredentialID: "ai_agent.webhook_secret",
			SecretKey: "AI_AGENT_WEBHOOK_SECRET", DesiredSecretKey: "CANDIDATE", Authority: "anas",
		},
	}
	resp, err := handle(req)
	if err != nil {
		t.Fatalf("credential_reconcile: %v", err)
	}
	if resp.Credential == nil || resp.Credential.Status != "match" {
		t.Fatalf("credential result = %+v, want a match", resp.Credential)
	}

	// A handler name that belongs to another credential must be refused rather
	// than quietly applied to this one.
	req.Credential.CredentialID = "ai_agent.forgejo_admin_password"
	if _, err := handle(req); err == nil {
		t.Fatal("the hook accepted a credential operation for a different credential")
	}
}

