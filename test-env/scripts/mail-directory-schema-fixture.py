RESULTS = []


def record(name, **details):
    row = {"check": name, "passed": True, **details}
    RESULTS.append(row)
    print(json.dumps(row), flush=True)


def local():
    lp = LoadParm(); lp.load_default()
    return SamDB(url="/var/lib/samba/private/sam.ldb", session_info=system_session(), lp=lp)


def connection(user):
    secret = json.loads(SECRETS.read_text())
    lp = LoadParm(); lp.load_default()
    creds = Credentials(); creds.guess(lp)
    creds.set_domain("MAILSCHEMA")
    creds.set_username(user); creds.set_password(secret[user])
    creds.set_kerberos_state(DONT_USE_KERBEROS)
    creds.set_gensec_features(creds.get_gensec_features() | gensec.FEATURE_SEAL)
    return SamDB(url="ldap://127.0.0.1", credentials=creds, lp=lp)


def modify(db, dn, attributes):
    change = ldb.Message(); change.dn = ldb.Dn(db, dn)
    for name, value in attributes.items():
        change[name] = ldb.MessageElement(value, ldb.FLAG_MOD_REPLACE, name)
    db.modify(change)


def deny(action, label):
    try:
        action()
    except ldb.LdbError as exc:
        assert exc.args[0] == ldb.ERR_INSUFFICIENT_ACCESS_RIGHTS, (label, exc.args[0])
    else:
        raise AssertionError("unauthorized operation succeeded: " + label)


def installer(*args, ok=True):
    p = subprocess.run(["python3", str(INSTALLER), *args], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    assert (p.returncode == 0) == ok, "schema command unexpected result: " + p.stdout + p.stderr
    return p


def mailbox(owner, kind, default, box_id=None):
    box_id = box_id or str(uuid.uuid4())
    cn = hashlib.sha256(("anas-primary-mailbox\n" + owner).encode()).hexdigest() if kind == "primary" else "mailbox-" + box_id
    return {"dn": "CN=" + cn + "," + BOXES, "objectClass": "anasMailbox", "cn": cn, "anasMailboxID": box_id, "anasMailOwnerAnchor": owner, "anasMailboxKind": kind, "anasMailDefaultAddress": default, "anasMailState": "pending", "anasMailConfigVersion": str(uuid.uuid4()), "anasMailOperationID": str(uuid.uuid4()), "anasMailOperationState": "reserved"}


def claim(address, owner, box_id):
    address = address.lower()
    cn = hashlib.sha256(address.encode()).hexdigest()
    return {"dn": "CN=" + cn + "," + ADDRESSES, "objectClass": "anasMailAddressClaim", "cn": cn, "anasMailboxID": box_id, "anasMailOwnerAnchor": owner, "anasMailAddress": address, "anasMailAddressKind": "alias", "anasMailState": "pending", "anasMailConfigVersion": str(uuid.uuid4()), "anasMailOperationID": str(uuid.uuid4()), "anasMailOperationState": "reserved"}


def provision():
    assert not Path("/var/lib/samba/private/sam.ldb").exists(), "refusing to provision over an existing domain"
    Path("/etc/samba/smb.conf").unlink(missing_ok=True)
    secret = json.loads(SECRETS.read_text())
    with Path("/evidence/provision.log").open("w") as log:
        p = subprocess.run(["samba-tool", "domain", "provision", "--realm=MAILSCHEMA.INVALID", "--domain=MAILSCHEMA", "--server-role=dc", "--dns-backend=NONE", "--use-rfc2307", "--host-name=dc", "--host-ip="+socket.gethostbyname(socket.gethostname()), "--option=posix:eadb=/var/lib/samba/eadb.tdb", "--adminpass="+secret["Administrator"]], stdout=log, stderr=log)
    assert p.returncode == 0, "isolated domain provisioning failed"
    # The reused image can disable autogenerated TLS. Generate a private fixture
    # CA and a SAN-bearing leaf explicitly; Go still validates chain and name.
    tls = Path("/var/lib/samba/private/tls")
    tls.mkdir(mode=0o700, exist_ok=True)
    extensions = tls / "extensions.cnf"
    extensions.write_text("subjectAltName=DNS:dc.mailschema.invalid,IP:127.0.0.1\nextendedKeyUsage=serverAuth\n")
    commands = [
        ["openssl","req","-x509","-newkey","rsa:2048","-nodes","-days","2","-subj","/CN=ANAS isolated mail test CA","-addext","basicConstraints=critical,CA:TRUE","-keyout",str(tls/"ca-key.pem"),"-out",str(tls/"ca.pem")],
        ["openssl","req","-new","-newkey","rsa:2048","-nodes","-subj","/CN=dc.mailschema.invalid","-keyout",str(tls/"key.pem"),"-out",str(tls/"request.pem")],
        ["openssl","x509","-req","-days","2","-in",str(tls/"request.pem"),"-CA",str(tls/"ca.pem"),"-CAkey",str(tls/"ca-key.pem"),"-CAcreateserial","-extfile",str(extensions),"-out",str(tls/"cert.pem")],
    ]
    for command in commands:
        generated = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        assert generated.returncode == 0, "isolated TLS generation failed"
    for path in tls.iterdir(): path.chmod(0o600)
    record("fresh_domain_provisioned")


def prepare():
    db = local()
    assert str(db.domain_dn()).lower() == BASE.lower(), "refusing non-fixture domain"
    loader = importlib.util.spec_from_file_location("mail_schema", INSTALLER)
    schema = importlib.util.module_from_spec(loader); loader.loader.exec_module(schema)
    spec = schema.load_spec()
    installer("--check", ok=False)
    directory = schema.Directory()
    original_add = directory.add
    written = 0
    def interrupted(values):
        nonlocal written
        if written == 5:
            raise ValueError("injected schema interruption")
        original_add(values); written += 1
    directory.add = interrupted
    try:
        schema.install(directory, spec, True)
    except ValueError as exc:
        if str(exc) != "injected schema interruption":
            differences = []
            for kind, section in (("attributeSchema","attributes"),("classSchema","classes")):
                for item in spec[section]:
                    wanted=schema.expected(item,kind,directory.context())
                    for row in directory.find(item,directory.context()):
                        if not schema.matches(row,wanted):
                            differences.append({"name":item["name"],"actual":{k:[schema.base64.b64encode(v).decode() for v in values] for k,values in row.items()},"expected":{k:[schema.base64.b64encode(v).decode() for v in values] for k,values in wanted.items()}})
            Path("/evidence/schema-mismatch.json").write_text(json.dumps(differences,indent=2))
            raise
    else:
        raise AssertionError("schema interruption not injected")
    assert written == 5
    installer("--check", ok=False)
    installer("--install")
    assert "installed=0" in installer("--install").stdout
    installer("--check")
    record("schema_install_resume_idempotency", definitions=15, interrupted_after=5)
    # Reopen after schema additions; this SamDB instance must load new classes.
    db = local()
    for dn in (PEOPLE, SERVICES):
        db.add({"dn": dn, "objectClass": "organizationalUnit"})
    secret = json.loads(SECRETS.read_text())
    users = {}
    for name in ("alice", "bob", "reader", "portal", "address", "primary", "outsider"):
        userou = "OU=Service Accounts" if name in ("reader", "portal", "address", "primary") else "OU=People"
        db.newuser(name, secret[name], userou=userou)
        row = db.search(base=BASE, expression="(sAMAccountName=" + name + ")", attrs=["objectGUID", "objectSid"])[0]
        anchor = str(uuid.UUID(bytes_le=bytes(row["objectGUID"][0])))
        modify(db, str(row.dn), {"mS-DS-ConsistencyGuid": bytes(row["objectGUID"][0]), "anasIdentityAnchor": anchor})
        users[name] = {"dn": str(row.dn), "anchor": anchor}
    # The Go mail reader uses an explicitly anchored allowed group, including
    # AD primary-group membership. This changes no membership or domain role.
    domain_users = db.search(base="CN=Domain Users,CN=Users,"+BASE, scope=ldb.SCOPE_BASE, attrs=["objectGUID"])[0]
    modify(db, str(domain_users.dn), {"mS-DS-ConsistencyGuid": bytes(domain_users["objectGUID"][0]), "anasIdentityAnchor": str(uuid.UUID(bytes_le=bytes(domain_users["objectGUID"][0])))})
    domain_sid = security.dom_sid(db.get_domain_sid())
    for name, user in users.items():
        row = db.search(base=user["dn"], scope=ldb.SCOPE_BASE, attrs=["objectSid"])[0]
        from samba.ndr import ndr_unpack
        user["sid"] = str(ndr_unpack(security.dom_sid, bytes(row["objectSid"][0])))
    # Exercise the actual operator bootstrap rather than fixture-written ACLs.
    os.environ["SAMBA_DC_BASE_DN"] = BASE
    path = INSTALLER.with_name("install-mail-directory.py")
    loader = importlib.util.spec_from_file_location("mail_directory", path)
    bootstrap = importlib.util.module_from_spec(loader); loader.loader.exec_module(bootstrap)
    config = {"base_dn": BASE, "people_dn": PEOPLE, "roles": {
        "reader": users["reader"]["dn"], "creator": users["portal"]["dn"], "address_writer": users["address"]["dn"], "primary_writer": users["primary"]["dn"]}}
    def bootstrap_cli(*args, ok=True, error=None):
        result = subprocess.run(["python3", str(path), *args], input=json.dumps(config), text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        assert (result.returncode == 0) == ok, "directory command unexpected result: " + result.stdout + result.stderr
        if error:
            assert error in result.stderr, "directory failure reason mismatch: " + result.stderr
        return result
    bootstrap_cli(ok=False, error="mail directory incomplete")
    acl_before = bytes(db.search(base=PEOPLE, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"])[0]["nTSecurityDescriptor"][0])
    # A late same-name foreign OU must stop all preparation before ACL writes.
    db.add({"dn": MAIL, "objectClass": "organizationalUnit", "description": "foreign fixture object"})
    bootstrap_cli("--prepare", ok=False, error="mail directory OU ownership or ACL drift")
    assert not db.search(base=BASE, expression="(ou=Mailboxes)", attrs=["1.1"])
    assert bytes(db.search(base=PEOPLE, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"])[0]["nTSecurityDescriptor"][0]) == acl_before
    db.delete(MAIL)
    record("directory_foreign_ou_refused_before_writes")
    # Real local transaction rollback, including an earlier OU Add.
    candidate = bootstrap.Directory()
    original = candidate.add_ou
    writes = 0
    def interrupted(dn, descriptor):
        nonlocal writes
        if writes == 1:
            raise ValueError("injected directory interruption")
        original(dn, descriptor); writes += 1
    candidate.add_ou = interrupted
    try: bootstrap.prepare(candidate, config, True)
    except ValueError as exc: assert str(exc) == "injected directory interruption"
    else: raise AssertionError("directory interruption not injected")
    assert not db.search(base=BASE, expression="(ou=Mail)", attrs=["1.1"])
    assert bytes(db.search(base=PEOPLE, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"])[0]["nTSecurityDescriptor"][0]) == acl_before
    record("directory_transaction_interruption_rolled_back")
    candidate = bootstrap.Directory()
    original_check = candidate.check_ou
    def diagnosed_check(dn, descriptor):
        try: return original_check(dn, descriptor)
        except ValueError:
            _, actual = candidate.descriptor(dn)
            Path("/evidence/directory-acl-mismatch.json").write_text(json.dumps({"dn": dn, "actual": actual.as_sddl(domain_sid), "expected": descriptor}, indent=2))
            raise
    candidate.check_ou = diagnosed_check
    assert bootstrap.prepare(candidate, config, True) == 21
    assert "changes=0" in bootstrap_cli("--prepare").stdout
    bootstrap_cli("--check")
    record("directory_prepare_readback_and_repeat", roles=4, managed_ous=3)
    # Role aliasing and a disabled service fail even on an otherwise ready tree.
    invalid = dict(config, roles=dict(config["roles"], reader=users["portal"]["dn"]))
    try: bootstrap.prepare(bootstrap.Directory(), invalid, True)
    except ValueError: pass
    else: raise AssertionError("shared reader/writer SID accepted")
    modify(db, users["reader"]["dn"], {"userAccountControl": "514"})
    bootstrap_cli("--prepare", ok=False, error="mail directory role must be an enabled ordinary")
    modify(db, users["reader"]["dn"], {"userAccountControl": "512"})
    bootstrap_cli("--check")
    for scope in (BOXES, PEOPLE):
        # Added privilege must be reported, not silently adopted or removed.
        row = db.search(base=scope, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"], controls=["sd_flags:1:4"])[0]
        original_sd = bytes(row["nTSecurityDescriptor"][0])
        from samba.ndr import ndr_unpack
        sd = ndr_unpack(security.descriptor, original_sd)
        sd.dacl_add(security.descriptor.from_sddl("D:(A;;GA;;;" + users["reader"]["sid"] + ")", domain_sid).dacl.aces[0])
        message = ldb.Message(); message.dn = ldb.Dn(db, scope)
        message["nTSecurityDescriptor"] = ldb.MessageElement(ndr_pack(sd), ldb.FLAG_MOD_REPLACE, "nTSecurityDescriptor")
        db.modify(message, controls=["sd_flags:1:4"])
        drifted = bytes(db.search(base=scope, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"], controls=["sd_flags:1:4"])[0]["nTSecurityDescriptor"][0])
        bootstrap_cli("--prepare", ok=False, error="mail directory OU ownership or ACL drift" if scope == BOXES else "mail directory unexpected existing service ACL")
        assert bytes(db.search(base=scope, scope=ldb.SCOPE_BASE, attrs=["nTSecurityDescriptor"], controls=["sd_flags:1:4"])[0]["nTSecurityDescriptor"][0]) == drifted
        message["nTSecurityDescriptor"] = ldb.MessageElement(original_sd, ldb.FLAG_MOD_REPLACE, "nTSecurityDescriptor")
        db.modify(message, controls=["sd_flags:1:4"])
    bootstrap_cli("--check")
    record("directory_acl_drift_refused_without_repair", scopes=2)
    os.environ["SAMBA_DC_DOMAIN_ACTION"] = "join"
    bootstrap_cli("--prepare", ok=False, error="mail directory joined DC is check-only")
    bootstrap_cli("--check")
    del os.environ["SAMBA_DC_DOMAIN_ACTION"]
    record("directory_invalid_role_refused")
    (Path("/var/lib/samba") / "mail-schema-fixture.json").write_text(json.dumps(users))
    record("fixture_acl_prepared", personnel=3, services=4, managed_ous=3, source="install-mail-directory.py")


def verify():
    db = local()
    assert str(db.domain_dn()).lower() == BASE.lower()
    users = json.loads(Path("/var/lib/samba/mail-schema-fixture.json").read_text())
    portal, reader, address_writer = connection("portal"), connection("reader"), connection("address")
    def imported(name):
        box = mailbox(users[name]["anchor"], "primary", name+"@mailschema.invalid", users[name]["mailbox_id"])
        return box
    primary = imported("alice")
    additional = mailbox(users["alice"]["anchor"], "additional", "project@mailschema.invalid")
    other = imported("bob")
    other_additional = mailbox(users["bob"]["anchor"], "additional", "bob-project@mailschema.invalid")
    portal.add(additional)
    portal.add(other_additional)
    connection("alice")  # Existing credentials still work after resource import.
    row = reader.search(base=primary["dn"], scope=ldb.SCOPE_BASE, attrs=["objectClass","anasIdentityAnchor","anasMailboxID","anasMailOwnerAnchor","sAMAccountName","unicodePwd","objectSid"])[0]
    assert bytes(row["anasMailOwnerAnchor"][0]).decode() == users["alice"]["anchor"]
    assert "anasIdentityAnchor" not in row and "sAMAccountName" not in row and "objectSid" not in row
    assert "user" not in [bytes(x).decode().lower() for x in row["objectClass"]]
    record("separate_non_login_mailbox_identity", primary_mailboxes=3, additional_mailboxes=2)
    deny(lambda: modify(reader, primary["dn"], {"anasMailState":"disabled"}), "read-only state update")
    deny(lambda: reader.add(claim("reader@mailschema.invalid", users["alice"]["anchor"], primary["anasMailboxID"])), "read-only claim create")
    deny(lambda: modify(reader, users["alice"]["dn"], {"mail":"forged@mailschema.invalid"}), "read-only personnel mail")
    deny(lambda: reader.delete(primary["dn"]), "read-only mailbox delete")
    record("mail_reader_write_denied", operations=4)
    deny(lambda: modify(portal, primary["dn"], {"anasMailboxID":str(uuid.uuid4())}), "mailbox ID mutation")
    deny(lambda: modify(portal, primary["dn"], {"anasMailOwnerAnchor":users["bob"]["anchor"]}), "mailbox owner mutation")
    deny(lambda: portal.add({"dn":"CN=forged,"+BOXES,"objectClass":"user","sAMAccountName":"forged"}), "create login user in mailbox OU")
    deny(lambda: modify(portal, users["alice"]["dn"], {"sAMAccountName":"renamed"}), "arbitrary personnel attribute")
    record("portal_fixed_scope_denied", operations=4)
    # Class defaults must keep the service from owning the resource it creates.
    from samba.ndr import ndr_unpack
    owner_row=reader.search(base=primary["dn"],scope=ldb.SCOPE_BASE,attrs=["nTSecurityDescriptor"],controls=["sd_flags:1:5"])[0]
    owner_sd=ndr_unpack(security.descriptor,bytes(owner_row["nTSecurityDescriptor"][0]))
    assert str(owner_sd.owner_sid)==db.get_domain_sid()+"-512", "mailbox creator became the object owner"
    # A creator must not acquire implicit WRITE_DAC on its mailbox object.
    sd = security.descriptor.from_sddl("D:(A;;GA;;;"+users["portal"]["sid"]+")", security.dom_sid(db.get_domain_sid()))
    change = ldb.Message(); change.dn=ldb.Dn(portal, primary["dn"])
    change["nTSecurityDescriptor"]=ldb.MessageElement(ndr_pack(sd),ldb.FLAG_MOD_REPLACE,"nTSecurityDescriptor")
    deny(lambda: portal.modify(change,controls=["sd_flags:1:4"]), "creator cannot replace mailbox ACL")
    record("creator_cannot_expand_acl")
    outsider = connection("outsider")
    try:
        rows = outsider.search(base=primary["dn"],scope=ldb.SCOPE_BASE,attrs=["anasMailOwnerAnchor"])
    except ldb.LdbError as exc:
        assert exc.args[0] in (ldb.ERR_INSUFFICIENT_ACCESS_RIGHTS,ldb.ERR_NO_SUCH_OBJECT)
    else:
        assert not rows or "anasMailOwnerAnchor" not in rows[0]
    record("unrelated_user_no_resource_read")
    proxy = ldb.Message(); proxy.dn = ldb.Dn(address_writer,users["alice"]["dn"])
    proxy["proxyAddresses"] = ldb.MessageElement(["smtp:shopping@mailschema.invalid"],ldb.FLAG_MOD_ADD,"proxyAddresses")
    deny(lambda: portal.modify(proxy), "creator cannot maintain aliases")
    address_writer.modify(proxy)
    deny(lambda: modify(address_writer, users["alice"]["dn"], {"mail":"wrong@mailschema.invalid"}), "address writer cannot replace system primary")
    deny(lambda: modify(address_writer, primary["dn"], {"anasMailOwnerAnchor":users["bob"]["anchor"]}), "address writer cannot transfer mailbox history")
    record("portal_personnel_proxy_write_allowed", creator_denied=True)
    # Keep CAS stress claims out of the imported primary boxes inspected by
    # the Go consumer. Pending claims are legitimate returned facts there.
    owner_boxes = [(additional, users["alice"]["anchor"]),(other_additional,users["bob"]["anchor"])]
    def reserve(i):
        target, owner = owner_boxes[i%2]
        candidate = claim("Race@MAILSCHEMA.INVALID" if i%2 else "race@mailschema.invalid",owner,target["anasMailboxID"])
        client=connection("portal")
        try: client.add(candidate); return True
        except ldb.LdbError as exc: assert exc.args[0] == ldb.ERR_ENTRY_ALREADY_EXISTS; return False
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
        winners=sum(pool.map(reserve,range(12)))
    assert winners==1
    address=claim("race@mailschema.invalid",users["alice"]["anchor"],primary["anasMailboxID"])
    row=reader.search(base=address["dn"],scope=ldb.SCOPE_BASE,attrs=["anasMailConfigVersion","anasMailAddress","anasMailboxID","anasMailOwnerAnchor"])[0]
    original=bytes(row["anasMailConfigVersion"][0]).decode()
    assert bytes(row["anasMailAddress"][0]).decode()=="race@mailschema.invalid"
    record("concurrent_address_add_one_winner", contenders=12, winners=winners)
    def cas(i):
        client=connection("portal")
        change = "dn: " + address["dn"] + "\nchangetype: modify\ndelete: anasMailConfigVersion\nanasMailConfigVersion: " + original + "\n-\nadd: anasMailConfigVersion\nanasMailConfigVersion: " + str(uuid.uuid4()) + "\n-\nreplace: anasMailOperationState\nanasMailOperationState: candidate-" + str(i) + "\n-\n"
        try: client.modify_ldif(change);return True
        except ldb.LdbError as exc: assert exc.args[0] in (ldb.ERR_NO_SUCH_ATTRIBUTE,ldb.ERR_ATTRIBUTE_OR_VALUE_EXISTS);return False
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
        winners=sum(pool.map(cas,range(12)))
    assert winners==1
    row=reader.search(base=address["dn"],scope=ldb.SCOPE_BASE,attrs=["anasMailConfigVersion","anasMailOperationState"])[0]
    version=bytes(row["anasMailConfigVersion"][0]).decode()
    stage=bytes(row["anasMailOperationState"][0]).decode()
    assert version!=original and stage.startswith("candidate-")
    # A stale comparison must roll back every modification in that request.
    bad = "dn: " + address["dn"] + "\nchangetype: modify\nreplace: anasMailOperationState\nanasMailOperationState: must-rollback\n-\ndelete: anasMailConfigVersion\nanasMailConfigVersion: " + original + "\n-\nadd: anasMailConfigVersion\nanasMailConfigVersion: " + str(uuid.uuid4()) + "\n-\n"
    try: portal.modify_ldif(bad)
    except ldb.LdbError as exc: assert exc.args[0] in (ldb.ERR_NO_SUCH_ATTRIBUTE,ldb.ERR_ATTRIBUTE_OR_VALUE_EXISTS)
    else: raise AssertionError("stale version succeeded")
    after=reader.search(base=address["dn"],scope=ldb.SCOPE_BASE,attrs=["anasMailConfigVersion","anasMailOperationState"])[0]
    assert bytes(after["anasMailConfigVersion"][0]).decode()==version
    assert bytes(after["anasMailOperationState"][0]).decode()==stage
    record("conditional_update_one_winner_and_atomic_rollback", contenders=12,winners=winners)
    installer("--check")
    record("schema_unchanged_after_ldap_operations")


def migrate():
    db = local()
    assert str(db.domain_dn()).lower() == BASE.lower()
    os.environ["SAMBA_DC_BASE_DN"] = BASE
    users = json.loads(Path("/var/lib/samba/mail-schema-fixture.json").read_text())
    path = INSTALLER.with_name("migrate-mail-primary.py")
    loader = importlib.util.spec_from_file_location("mail_primary_migration", path)
    migration = importlib.util.module_from_spec(loader); loader.loader.exec_module(migration)
    config = {"base_dn": BASE, "people_dn": PEOPLE, "mail_domain": "mailschema.invalid", "roles": {
        "reader": users["reader"]["dn"], "creator": users["portal"]["dn"], "address_writer": users["address"]["dn"], "primary_writer": users["primary"]["dn"]}}
    # The owner anchor can differ from AD objectGUID. Import must bind both.
    anchor = uuid.uuid4()
    modify(db, users["alice"]["dn"], {"mS-DS-ConsistencyGuid":anchor.bytes_le,"anasIdentityAnchor":str(anchor)})
    users["alice"]["anchor"] = str(anchor)
    for name in ("alice", "bob", "outsider"):
        modify(db, users[name]["dn"], {"mail":name+"@mailschema.invalid"})
    modify(db, users["alice"]["dn"], {"proxyAddresses":["smtp:legacy-alias@mailschema.invalid","X500:/legacy"]})
    def cli(*args, ok=True, error=None):
        result = subprocess.run(["python3",str(path),*args],input=json.dumps(config),text=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
        assert (result.returncode == 0) == ok, "migration command unexpected result: "+result.stdout+result.stderr
        if error: assert error in result.stderr, result.stderr
        return json.loads(result.stdout) if ok else None
